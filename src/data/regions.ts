  awsRegions.filter((r) => r.status === 'operational');

export const getTotalResources = (): number =>
  awsRegions.reduce((sum, r) => sum + r.resources, 0);

export const getTotalMonthlyCost = (): number =>
  awsRegions.reduce((sum, r) => sum + r.monthlyCost, 0);
